	public static Vector3 MoveTowards(Vector3 current, Vector3 target, float maxDistanceDelta)
	{
		Vector3 vector = target - current;
		float num = vector.Length();
		if (num <= maxDistanceDelta || num <= get_kEpsilon())
		{
			return target;
		}
		return current + vector / num * maxDistanceDelta;
	}

	public static Vector3 ProjectOnPlane(Vector3 vector, Vector3 planeNormal)
	{
		float num = Vector3.Dot(planeNormal, planeNormal);
		if (num < get_kEpsilon())
		{
			return vector;
		}
		return vector - planeNormal * (Vector3.Dot(vector, planeNormal) / num);
	}

